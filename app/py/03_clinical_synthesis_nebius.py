@trace_call("classify_case", log_args=True, log_result=True)
def classify_case(text: str) -> str:
    """Selects the clinical branch that best matches the intake (English keywords)."""
    t = text.lower()
    if any(k in t for k in ["amlodip", "calcium channel", "calcium-channel", "blister", "ccb"]):
        return "amlodipine"
    if any(k in t for k in ["rabbit", "lagomorph", "gi stasis", "stasis", "cecal", "anorexia"]):
        return "rabbit"
    if any(k in t for k in ["lameness", "tick", "lyme", "borrelia", "anaplasma", "vector-borne"]):
        return "tick"
    if any(k in t for k in ["cat", "feline", "lily", "lilium", "cut flower", "flower"]):
        return "lily"
    if any(k in t for k in ["ferret", "mustelid", "status epilepticus", "seizure", "convuls"]):
        return "ferret"
    return "chocolate"

