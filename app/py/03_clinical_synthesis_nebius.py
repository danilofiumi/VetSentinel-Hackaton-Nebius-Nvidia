@trace_call("_valid_synthesis", log_args=False, log_result=True)
def _valid_synthesis(data):
    """Minimal structural validation of an LLM-produced synthesis object with detailed diagnostic logging."""
    if not isinstance(data, dict):
        log_warning(f"Validation rejected: response is not a dict (got {type(data).__name__})")
        return False
    if not data.get("presumptive_diagnosis"):
        log_warning("Validation rejected: missing 'presumptive_diagnosis' key or value is empty")
        return False
    proto = data.get("immediate_intervention_protocol")
    if not isinstance(proto, dict):
        log_warning(f"Validation rejected: 'immediate_intervention_protocol' is not a dict (got {type(proto).__name__})")
        return False
    required_proto_keys = {"emesis_induction", "activated_charcoal", "specific_antidote"}
    missing_proto = required_proto_keys - set(proto.keys())
    if missing_proto:
        log_warning(f"Validation rejected: 'immediate_intervention_protocol' is missing mandatory keys: {missing_proto}")
        return False
    table = data.get("dosage_calculation_table")
    if not isinstance(table, list) or not table:
        log_warning(f"Validation rejected: 'dosage_calculation_table' must be a non-empty list (got {type(table).__name__}, len={len(table) if isinstance(table, list) else 'N/A'})")
        return False
    return True

@trace_call("synthesize_with_llm", log_args=True)
def synthesize_with_llm(patient, documents, model_name, language: str = "en"):
    """Evidence-grounded synthesis: feeds the retrieved documents back into the
    Nebius LLM to produce the protocol. Returns None if unavailable/invalid so
    the caller can fall back to the deterministic clinical rules."""
    api_key = get_parameter("NEBIUS_API_KEY")
    if not api_key:
        log_warning("NEBIUS_API_KEY is not configured or resolved. Cannot perform live synthesis inference; using deterministic rules.")
        return None
    if not documents:
        log_warning("No clinical search documents provided from Step 2. Cannot ground synthesis; using deterministic rules.")
        return None

    weight = float(patient.get("weight_kg", 4.0))
    evidence = "\n\n".join(
        f"[{i + 1}] {d.get('source_name') or d.get('source_domain', 'source')} — {d.get('title', '')}\n"
        f"URL: {d.get('url', '')}\n"
        f"{(d.get('cleaned_markdown') or d.get('content', ''))[:1200]}"
        for i, d in enumerate(documents[:6])
    )

    language_name = resolve_language_name(language)
    system_prompt = render_prompt(
        "clinical_synthesis",
        "system_prompt",
        fallback="You are a veterinary clinical synthesis engine. Respond only with a valid JSON object, grounded in the provided evidence. Write every human-readable prose value in {language_name}.",
        language_name=language_name,
    )
    prompt = render_prompt(
        "clinical_synthesis",
        "user_prompt",
        species=patient.get("species"),
        breed=patient.get("breed"),
        weight=weight,
        priority=patient.get("priority"),
        symptoms=patient.get("symptoms"),
        evidence=evidence,
        language_name=language_name,
    )

    synthesis_model = get_parameter("NEBIUS_SYNTHESIS_MODEL", get_parameter("NEBIUS_MODEL", "zai-org/GLM-5.3"))
    raw_timeout = get_parameter("NEBIUS_SYNTHESIS_TIMEOUT", get_parameter("NEBIUS_TIMEOUT", "60.0"))
    try:
        timeout_sec = float(raw_timeout)
    except Exception as te:
        log_warning(f"Could not convert timeout '{raw_timeout}' to float ({te}), using 60.0s")
        timeout_sec = 60.0

    candidate_models = resolve_candidate_models(synthesis_model, "synthesis")
    url = get_parameter("NEBIUS_API_URL", "https://api.studio.nebius.ai/v1/chat/completions")
    temperature = float(get_parameter("NEBIUS_SYNTHESIS_TEMPERATURE", "0.1"))
    max_tokens = int(get_parameter("NEBIUS_SYNTHESIS_MAX_TOKENS", "80000"))
    resp_format = get_parameter("NEBIUS_SYNTHESIS_RESPONSE_FORMAT", "json_object")

    for cand_idx, cand in enumerate(candidate_models):
        req_start = time.time()
        headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
        payload = {
            "model": cand,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ],
            "response_format": {"type": resp_format},
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        is_longtail = (cand_idx == len(candidate_models) - 1) and len(candidate_models) > 1
        cand_timeout = None if is_longtail else timeout_sec

        if is_longtail:
            console.print(
                f"[cyan]Initiating Nebius Clinical Synthesis attempt {cand_idx + 1}/{len(candidate_models)} "
                f"on long-tail fallback model: [bold green]{cand}[/bold green] "
                f"([bold yellow]NO TIMEOUT — Waiting until completion[/bold yellow])...[/cyan]"
            )
        else:
            console.print(
                f"[cyan]Initiating Nebius Clinical Synthesis attempt {cand_idx + 1}/{len(candidate_models)} "
                f"on [bold]{cand}[/bold] (timeout={int(timeout_sec)}s)...[/cyan]"
            )
        log_http_request(provider="Nebius Synthesis", url=url, method="POST", headers=headers, payload=payload, timeout=cand_timeout)

        try:
            with httpx.Client(timeout=cand_timeout) as client:
                resp = client.post(url, headers=headers, json=payload)
                req_duration = (time.time() - req_start) * 1000

                if resp.status_code == 200:
                    resp_json = resp.json()
                    choice = resp_json.get("choices", [{}])[0]
                    finish_reason = choice.get("finish_reason", "unknown")
                    content = choice.get("message", {}).get("content", "")
                    usage = resp_json.get("usage")

                    log_http_response(
                        provider=f"Nebius Synthesis ({cand})",
                        status_code=200,
                        elapsed_ms=req_duration,
                        headers=resp.headers,
                        body=resp_json,
                        finish_reason=finish_reason,
                        usage=usage
                    )

                    if finish_reason == "length":
                        log_warning(f"Nebius synthesis hit max_tokens limit on candidate {cand}. Attempting next model...")
                        continue
                    if not content or not content.strip():
                        log_warning(f"Nebius synthesis returned empty content on candidate {cand}. Attempting next model...")
                        continue

                    cleaned_content = content.strip()
                    if cleaned_content.startswith("```json"):
                        cleaned_content = cleaned_content[7:]
                    elif cleaned_content.startswith("```"):
                        cleaned_content = cleaned_content[3:]
                    if cleaned_content.endswith("```"):
                        cleaned_content = cleaned_content[:-3]
                    cleaned_content = cleaned_content.strip()

                    try:
                        data = json.loads(cleaned_content)
                    except json.JSONDecodeError as jde:
                        log_warning(f"Decoding JSON synthesis error on candidate '{cand}': {jde}. Attempting next model...")
                        console.print(f"[dim yellow]Raw unparseable content preview (first 500 chars):[/dim yellow]\n{cleaned_content[:500]}")
                        continue

                    if _valid_synthesis(data):
                        data["model_used"] = cand
                        log_success(f"Evidence-grounded synthesis produced by Nebius ({cand}) in {req_duration:.0f}ms")
                        return data
                    log_warning(f"LLM synthesis on candidate {cand} failed validation checks. Attempting next candidate...")
                else:
                    log_http_response(
                        provider=f"Nebius Synthesis ({cand})",
                        status_code=resp.status_code,
                        elapsed_ms=req_duration,
                        headers=resp.headers,
                        body=resp.text
                    )
        except httpx.TimeoutException as toe:
            req_duration = (time.time() - req_start) * 1000
            if is_longtail:
                log_warning(f"Nebius synthesis timed out on long-tail model '{cand}' after {req_duration:.0f}ms.")
            else:
                log_warning(f"Nebius synthesis timed out after {req_duration:.0f}ms on {cand} (configured timeout: {int(timeout_sec)}s). Attempting next model...")
        except httpx.HTTPError as he:
            if is_longtail:
                log_warning(f"Nebius synthesis HTTP transport error on long-tail model '{cand}': {he}")
            else:
                log_warning(f"Nebius synthesis HTTP transport error on {cand}: {he}. Attempting next model...")
        except Exception as e:
            log_exception(e, f"Nebius synthesis unexpected exception on {cand}")

    log_warning("All LLM candidate synthesis models failed or timed out; falling back to deterministic clinical rules.")
    return None

